"""
Setup Supabase Database Schema for AV Corporate giftings & events B2B RFQ Submissions
"""

import os
import urllib.request
import json

ACCESS_TOKEN = os.environ.get("SUPABASE_ACCESS_TOKEN", "")
PROJECT_ID = os.environ.get("SUPABASE_PROJECT_ID", "yhitcudkupmqjzkrguno")
API_URL = f"https://api.supabase.com/v1/projects/{PROJECT_ID}/database/query"

MIGRATION_SQL = """
create extension if not exists pgcrypto;

create table if not exists public.quote_requests (
  id uuid primary key default gen_random_uuid(),
  session_hash text not null,
  full_name text not null,
  email text not null,
  company text not null,
  phone text default '',
  delivery_city text default '',
  target_date text default '',
  notes text default '',
  item_count integer not null default 0,
  total_quantity integer not null default 0,
  status text not null default 'new',
  created_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.quote_request_items (
  id bigint generated by default as identity primary key,
  request_id uuid not null references public.quote_requests(id) on delete cascade,
  product_id text not null,
  sku text not null,
  product_name text not null,
  category text not null,
  variant text default '',
  branding_method text default '',
  quantity integer not null default 1,
  image_url text default '',
  notes text default '',
  created_at timestamptz not null default now()
);

alter table public.quote_requests enable row level security;
alter table public.quote_request_items enable row level security;

drop policy if exists "Allow anonymous insert into quote_requests" on public.quote_requests;
create policy "Allow anonymous insert into quote_requests"
on public.quote_requests for insert
to anon, authenticated
with check (true);

drop policy if exists "Allow anonymous insert into quote_request_items" on public.quote_request_items;
create policy "Allow anonymous insert into quote_request_items"
on public.quote_request_items for insert
to anon, authenticated
with check (true);

drop policy if exists "Allow select for all" on public.quote_requests;
drop policy if exists "Allow select for authenticated" on public.quote_requests;
create policy "Allow select for all"
on public.quote_requests for select
to anon, authenticated, service_role
using (true);

drop policy if exists "Allow select items for all" on public.quote_request_items;
drop policy if exists "Allow select items for authenticated" on public.quote_request_items;
create policy "Allow select items for all"
on public.quote_request_items for select
to anon, authenticated, service_role
using (true);

drop policy if exists "Allow update for all" on public.quote_requests;
create policy "Allow update for all"
on public.quote_requests for update
to anon, authenticated, service_role
using (true)
with check (true);

drop policy if exists "Allow delete for all" on public.quote_requests;
create policy "Allow delete for all"
on public.quote_requests for delete
to anon, authenticated, service_role
using (true);

"""

def main():
    print(f"Applying schema migration to Supabase project {PROJECT_ID}...")
    req = urllib.request.Request(
        API_URL,
        data=json.dumps({"query": MIGRATION_SQL}).encode(),
        headers={
            "Authorization": f"Bearer {ACCESS_TOKEN}",
            "Content-Type": "application/json"
        }
    )

    try:
        with urllib.request.urlopen(req) as resp:
            print(f"Migration applied successfully! HTTP Status: {resp.status}")
    except Exception as e:
        print(f"Migration failed: {e}")

if __name__ == "__main__":
    main()
